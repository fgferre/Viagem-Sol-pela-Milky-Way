/** os conjuntos de um cometa, em ordem de passagem */
export function conjuntosDoCometa(id: string): readonly ConjuntoOsculante[] {
  return ELEMENTOS[id] ?? [];
}

/** o conjunto que vale em `jd`: o de época mais perto */
export function conjuntoVigente(id: string, jd: number): ConjuntoOsculante | null {
  const lista = ELEMENTOS[id];
  if (!lista || lista.length === 0 || !Number.isFinite(jd)) return null;
  let melhor = lista[0];
  for (const c of lista) if (Math.abs(c[0] - jd) < Math.abs(melhor[0] - jd)) melhor = c;
  return melhor;
}

/** a matriz perifocal → eclíptica, Rz(Ω)·Rx(i)·Rz(ω), como dois vetores */
function eixosPerifocais(c: ConjuntoOsculante): [number[], number[]] {
  const i = c[3] * D2R;
  const O = c[4] * D2R;
  const w = c[5] * D2R;
  const cO = Math.cos(O);
  const sO = Math.sin(O);
  const ci = Math.cos(i);
  const si = Math.sin(i);
  const cw = Math.cos(w);
  const sw = Math.sin(w);
  const P = [cO * cw - sO * sw * ci, sO * cw + cO * sw * ci, sw * si];
  const Q = [-cO * sw - sO * cw * ci, -sO * sw + cO * cw * ci, cw * si];
  return [P, Q];
}

const _perielios = new WeakMap<ConjuntoOsculante, number[]>();

/** o estado [Tp, r, v] no periélio da cônica — o ponto de partida */
function estadoNoPerielio(c: ConjuntoOsculante): number[] {
  const pronto = _perielios.get(c);
  if (pronto) return pronto;
  const [P, Q] = eixosPerifocais(c);
  const q = c[1];
  const v = Math.sqrt((MU_SOL * (1 + c[2])) / q);
  const e = [c[6], q * P[0], q * P[1], q * P[2], v * Q[0], v * Q[1], v * Q[2]];
  _perielios.set(c, e);
  return e;
}

/**
 * ONDE ESTÁ O COMETA no instante `jd` (JD TDB): [x, y, z, vx, vy, vz]
 * heliocêntricos, eclíptica J2000, UA e UA/dia — o frame das sondas e
 * dos corpos. `null` só para id desconhecido ou data não finita.
 */
export function estadoDoCometa(id: string, jd: number): number[] | null {
  const c = conjuntoVigente(id, jd);
  return c ? propagarKepler(estadoNoPerielio(c), jd) : null;
}

/** semieixo maior (UA) — negativo na hipérbole */
export function semieixo(c: ConjuntoOsculante): number {
  return c[1] / (1 - c[2]);
}

/** o período (dias) da cônica; `null` se ela não fecha */
export function periodoEmDias(c: ConjuntoOsculante): number | null {
  if (c[2] >= 1) return null;
  const a = semieixo(c);
  return 2 * Math.PI * Math.sqrt((a * a * a) / MU_SOL);
}

/** a posição na cônica do conjunto pela anomalia excêntrica (E) ou
 *  hiperbólica (H) — é assim que a linha da órbita se amostra */
export function pontoDaConica(c: ConjuntoOsculante, anomalia: number): [number, number, number] {
  const [P, Q] = eixosPerifocais(c);
  const e = c[2];
  const a = semieixo(c);
  let x: number;
  let y: number;
  if (e < 1) {
    const b = a * Math.sqrt(1 - e * e);
    x = a * (Math.cos(anomalia) - e);
    y = b * Math.sin(anomalia);
  } else {
    const b = -a * Math.sqrt(e * e - 1);
    x = a * (Math.cosh(anomalia) - e);
    y = b * Math.sinh(anomalia);
  }
  return [x * P[0] + y * Q[0], x * P[1] + y * Q[1], x * P[2] + y * Q[2]];
}

/**
 * O ÚLTIMO E O PRÓXIMO PERIÉLIO em torno de `jd`: os Tp da tabela e,
 * fora dela, um período antes ou depois (`derivado: true`). Na hipérbole
 * só existe uma passagem.
 */
export function perieliosEmVolta(
  id: string,
  jd: number
): { ultimo: { jd: number; derivado: boolean } | null; proximo: { jd: number; derivado: boolean } | null } {
  const lista = ELEMENTOS[id] ?? [];
  let ultimo: { jd: number; derivado: boolean } | null = null;
  let proximo: { jd: number; derivado: boolean } | null = null;
  for (const c of lista) {
    // só os conjuntos de PASSAGEM: os da grade de dez anos têm um Tp
    // osculante que anda com a data e não é passagem nenhuma
    if (Math.abs(c[0] - c[6]) > 400) continue;
    if (c[6] <= jd && (!ultimo || c[6] > ultimo.jd)) ultimo = { jd: c[6], derivado: false };
    if (c[6] > jd && (!proximo || c[6] < proximo.jd)) proximo = { jd: c[6], derivado: false };
  }
  const vigente = conjuntoVigente(id, jd);
  const P = vigente ? periodoEmDias(vigente) : null;
  if (P !== null && vigente) {
    if (!proximo && ultimo) proximo = { jd: ultimo.jd + P, derivado: true };
    if (!ultimo && proximo) ultimo = { jd: proximo.jd - P, derivado: true };
  }
  return { ultimo, proximo };
}

/** o corte da sublimação da água: o fator de g(r) de Marsden et al. 1973 */
export function corteDaAgua(r: number): number {
  return (1 + (r / 2.808) ** 5.093) ** -4.6142;
}

const CORTE_EM_1_UA = corteDaAgua(1);

/**
 * A PRODUÇÃO DE POEIRA E GÁS a `r` UA, relativa à de 1 UA: o brilho da
 * lei de potência (r^(−K1/2,5)) sem o 1/r² da luz do Sol, vezes o corte
 * da água. Quem desenha multiplica pelo 1/r² do lugar de cada grão.
 */
export function producaoRelativa(r: number, K1: number): number {
  if (!(r > 0)) return 0;
  return r ** (2 - K1 / 2.5) * (corteDaAgua(r) / CORTE_EM_1_UA);
}

/** a escala absoluta do cometa: 10^(−0,4 (M1 − 5)) — Halley ≈ 0,6 */
export function escalaDoBrilho(M1: number): number {
  return 10 ** (-0.4 * (M1 - 5));
}

/**
 * O cometa está ACESO em `r`? O brilho da coma a 1 UA da câmera,
 * relativo a um cometa de M1 = 5 a 1 UA do Sol — abaixo de 1e-4 (dez
 * magnitudes mais fraco) não há o que desenhar.
 */
export function brilhoRelativo(c: Cometa, r: number): number {
  return (escalaDoBrilho(c.brilho.M1) * producaoRelativa(r, c.brilho.K1)) / (r * r);
}

