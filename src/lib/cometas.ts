  /** a designação oficial (IAU/MPC) */
  designacao: string;
  /** o que a busca reconhece além do nome */
  apelidos: readonly string[];
  /** magnitude absoluta total e a inclinação da lei de potência */
  brilho: { M1: number; K1: number; fonte: string };
