// OS COMETAS — a tabela dos oito primeiros (pilar 4 do NORTE, "cometas
// com cauda", 12/11/2026), a conta que os põe no lugar em qualquer data
// e a lei de atividade que acende a coma e as caudas.
//
// O DADO: elementos osculantes heliocêntricos (eclíptica J2000, UA, JD
// TDB) do JPL Horizons, consultado em 2026-11-12: UM CONJUNTO POR
// PASSAGEM PELO PERIÉLIO entre 1900 e 2100 (a época é a passagem) e,
// para os de período longo ou sem volta (Halley, Swift–Tuttle,
// Pons–Brooks, Hale–Bopp, NEOWISE, 3I), mais um a cada dez anos — longe
// do Sol, perto do afélio, é Júpiter quem mais entorta a cônica. Os
// pedidos, iguais para os oito:
//   COMMAND='DES=<designação>;CAP' CENTER='500@10' REF_PLANE=ECLIPTIC
//   REF_SYSTEM=ICRF OUT_UNITS=AU-D EPHEM_TYPE=ELEMENTS, primeiro numa
//   grade de 1899-06-01 a 2100-06-01 (passo ~P/8) para achar os Tp, e
//   depois TLIST nos Tp achados; a grade de dez anos é STEP_SIZE='10 y'
//   de 1900-01-01 a 2100-01-01. As soluções orbitais são as do SBDB
//   que o Horizons usa (JPL#75 Halley, #K273/29 Encke, #K284/1 67P, #32
//   Swift–Tuttle, #K242/85 Pons–Brooks, #226 Hale–Bopp, #31 NEOWISE,
//   #55 3I/ATLAS), integradas pelo Horizons com os planetas e, onde a
//   solução as tem, as forças não gravitacionais.
// Nada de rede em tempo de uso e nada em `public/data`.
//
// A CONTA: vale o conjunto cuja ÉPOCA está mais perto da data, e o
// cometa segue a cônica dele (Kepler de dois corpos em variáveis
// universais, `propagarKepler` das sondas — a mesma função serve à
// elipse, à quase-parábola de Hale–Bopp e NEOWISE e à hipérbole de
// 3I/ATLAS). O ERRO cresce longe da passagem: Júpiter e os jatos do
// próprio núcleo mudam a órbita, e um conjunto só conhece o seu
// instante. Medido contra o Horizons em 2026-11-12 (`cometas.test.ts`).
//
// A ATIVIDADE (`producaoRelativa`): a lei de potência das magnitudes
// totais, m = M1 + 5 log Δ + K1 log r, com M1 e K1 publicados, dá o
// brilho; a produção que alimenta as caudas é esse brilho sem o 1/r² da
// luz do Sol, e o gelo de água só sublima dentro de ~3 UA — o corte é o
// fator (1 + (r/r0)^n)^−k da curva g(r) de Marsden, Sekanina & Yeomans
// (1973, AJ 78, 211: r0 = 2,808 UA, n = 5,093, k = 4,6142).
// ============================================================
